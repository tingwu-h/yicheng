/* ---------- 坐标查询辅助（供地图引擎与页面使用） ----------
   函数声明会被提升，故可写在数据声明之前；函数体在调用时才读取
   REGIONS / attractions，不会触发暂时性死区。 */

/* 取单个景点的地理坐标；未收录返回 null */
export function getGeo(id) {
  const item = attractions.find((a) => a.id === id)
  return item && item.geo ? item.geo : null
}

/* 按 id 列表取地图点位（保持入参顺序、跳过未知 id），字段与 MapCanvas 的 points 对齐 */
export function pointsForIds(ids) {
  if (!Array.isArray(ids)) return []
  return ids.reduce((list, id) => {
    const item = attractions.find((a) => a.id === id)
    if (!item || !item.geo) return list
    const region = REGIONS.find((r) => r.key === item.region)
    list.push({
      id: item.id,
      name: item.name,
      region: item.region,
      regionName: region ? region.name : '',
      color: region ? region.color : '#666666',
      type: item.type,
      lat: item.geo.lat,
      lng: item.geo.lng,
    })
    return list
  }, [])
}

/* 取片区地理中心坐标；未知 key 回退到第一个片区 */
export function regionGeo(key) {
  const region = REGIONS.find((r) => r.key === key) || REGIONS[0]
  return region && region.geo ? region.geo : null
}

