import assert from 'node:assert/strict'
import { readFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { attractions } from '../src/data/attractions.js'
import { postCoverImage, routeCoverImage } from '../src/data/community.js'

const root = new URL('../', import.meta.url)
const read = (path) => readFileSync(new URL(path, root), 'utf8')
assert.equal(attractions.length, 24)
for (const attraction of attractions) {
  assert.equal(attraction.image, `/images/attractions/${attraction.id}.jpg`)
  const image = readFileSync(new URL(`public${attraction.image}`, root))
  assert.equal(image[0], 0xff, `${attraction.id}: JPEG signature`)
  assert.equal(image[1], 0xd8, `${attraction.id}: JPEG signature`)
  assert.ok(image.length > 1000)
}
assert.ok(existsSync(fileURLToPath(new URL('public/images/attractions/CREDITS.md', root))))
assert.equal(postCoverImage({ attraction: 'a1' }), attractions.find(a => a.id === 'a1').image)
assert.equal(postCoverImage({}), undefined)
assert.equal(routeCoverImage({ stops: ['a4'] }), attractions.find(a => a.id === 'a4').image)
assert.equal(routeCoverImage({ stops: [] }), undefined)
assert.ok(read('src/components/cards.jsx').includes('/itinerary?route=${route.id}'))
assert.ok(read('src/pages/Home.jsx').includes('to="/notebook"'))
assert.ok(!read('src/pages/Home.jsx').includes('<ExplorationBoard'))
assert.ok(read('src/components/TopNav.jsx').includes("{ to: '/notebook', label: '手札' }"))
assert.ok(!read('src/pages/Home.jsx').includes('href="#exploration-notebook"'))
assert.ok(read('src/components/ExplorationBoard.jsx').includes('/tasks?tab=guide'))
assert.ok(read('src/components/ui.jsx').includes('onError={() => setBrokenSrc(src)}'))
assert.equal(JSON.parse(read('package.json')).version, '0.7.0')
assert.ok(read('src/pages/Home.jsx').includes('>✦ 探索入口</span>'))
assert.ok(!read('src/pages/Home.jsx').includes('RPG 探索入口'))
const css = read('src/styles/vh05.css')
const wave = css.split('@keyframes pet-wave {')[1].split('@keyframes pet-nod')[0]
const frames = [...wave.matchAll(/(\d+)%\s*\{\s*transform: rotate\((-?\d+)deg\)/g)].map(m => ({ percent: Number(m[1]), angle: Number(m[2]) }))
assert.equal(frames[0].angle, 0)
assert.equal(frames.at(-1).angle, 0)
assert.equal(frames.at(-1).percent, 100)
const raised = frames.slice(1, -1)
assert.ok(raised.every(f => f.angle <= -120 && f.angle >= -170), 'Raised hand must stay above the shoulder while waving')
const directions = raised.slice(1).map((f, i) => Math.sign(f.angle - raised[i].angle))
assert.ok(directions.every((d, i) => d !== 0 && (i === 0 || d !== directions[i - 1])), 'Wave must alternate sideways, not just hold still')
assert.ok(css.includes('animation: pet-wave 2s ease-in-out both'))
assert.ok(read('src/components/WalkingPet.jsx').includes("name === 'wave' ? 2050 : 1250"), 'Idle timeout must exceed the complete wave animation')
assert.ok(read('src/components/WalkingPet.jsx').includes('key={action.tick}'), 'Repeated clicks must restart the animation')
assert.ok(css.includes('animation: pet-five 1.2s ease-in-out both'), 'Keep the high-five timing unchanged')
const slideshow = read('src/components/HeroSlideshow.jsx')
const pageStyles = read('src/styles/pages.css')
const rotation = read('src/lib/heroRotation.js')
assert.ok(rotation.includes('HERO_INTERVAL_MS = 3000'))
assert.ok(slideshow.includes('[slides[slides.length-1],...slides,slides[0]]'), 'Duplicate both ends of the continuous ribbon for seamless wrap')
assert.ok(slideshow.includes('HERO_SLIDE_MS = 18000'), 'Keep the later slow continuous panorama requirement')
assert.ok(slideshow.includes('slides.every(item=>loaded.includes(item.id))'), 'Wait for ribbon images to load')
assert.ok(rotation.includes('clock.clearInterval(timer)'))
assert.ok(slideshow.includes("document.removeEventListener('visibilitychange',sync)"))
assert.ok(pageStyles.includes('prefers-reduced-motion: reduce'))
assert.ok(!slideshow.includes('reducedMotion'), 'Reduced motion must not stop rotation or hide the control')
assert.ok(rotation.includes('paused || !visible'))
assert.ok(pageStyles.includes('linear infinite'))
assert.ok(pageStyles.includes('transform:translateX(var(--ribbon-distance))'))
console.log('vh06-merge-selftest: ok (24 photos, routes, wave, scenic slideshow cadence/direction/cleanup)')
